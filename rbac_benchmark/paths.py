"""
paths.py — Central filesystem resolver for the benchmark's data artifacts.

Before packaging, every module computed its own ``_MASTER_DIR = Path(__file__).parent``
and read/wrote JSON next to itself. Once the code is split across subpackages that no
longer works (each module sits in a different directory), so all runtime data files are
resolved here through a single ``DATA_DIR``.

DATA_DIR defaults to ``<repo root>/data`` and can be overridden with the
``RBAC_DATA_DIR`` environment variable — handy for tests, CI, or pointing a run at a
scratch directory without touching the committed seed files. The directory is created
on import so callers never have to guard against it being missing.

Data files that live here:
    generated_injections.json   — red-team payloads (tracked seed; regenerated by the generator)
    generated_defenses.json     — blue-team prompts (tracked seed)
    custom_prompts.json         — user-added system prompts (runtime)
    benchmark_results.json      — primary results matrix + checkpoints (runtime)
    kappa_samples.json          — Phase-3 annotation worksheet (runtime)
    temp_run_config.json        — config the GUI hands to the master subprocess (runtime)
"""
from __future__ import annotations

import os
from pathlib import Path

# rbac_benchmark/paths.py -> rbac_benchmark/ -> repo root
_PKG_DIR = Path(__file__).resolve().parent
REPO_ROOT = _PKG_DIR.parent

DATA_DIR = Path(os.environ.get("RBAC_DATA_DIR", REPO_ROOT / "data"))
DATA_DIR.mkdir(parents=True, exist_ok=True)


def data_path(filename: str) -> str:
    """Returns the absolute path (as a str) to ``filename`` inside DATA_DIR."""
    return str(DATA_DIR / filename)
